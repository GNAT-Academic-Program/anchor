#!/usr/bin/env python3
"""Create a signing key pair for development.

    python3 tools/keygen.py            # refuses to overwrite an existing key
    python3 tools/keygen.py --force

Writes:
    keys/dev_signing.key                  the PRIVATE key, stays on the laptop
    src/crypto/anchor-trust_anchor.ads    the PUBLIC key, compiled into the
                                          bootloader (its "trust anchor")

After running this, rebuild the bootloader AND re-pack every image:
images signed with the old key are no longer trusted.
"""

import argparse
import os
import sys

import ed25519

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEY_PATH = os.path.join(ROOT, "keys", "dev_signing.key")
ADS_PATH = os.path.join(ROOT, "src", "crypto", "anchor-trust_anchor.ads")

ADS_TEMPLATE = """\
--  GENERATED by tools/keygen.py. Do not edit by hand.
--
--  The trust anchor: the one public key this bootloader believes.
--  Everything the device trusts is rooted here. It is compiled into the
--  bootloader, which lives in flash the update process never writes.
--
--  The matching private key is keys/dev_signing.key. It is a TEST key,
--  committed on purpose so the seed works out of the box.

with Anchor.Crypto;

package Anchor.Trust_Anchor with
  SPARK_Mode
is

   Public_Key : constant Crypto.Public_Key :=
     ({bytes});

end Anchor.Trust_Anchor;
"""


def ada_bytes(data, indent="      "):
    items = [f"16#{b:02X}#" for b in data]
    lines = [", ".join(items[i:i + 8]) for i in range(0, len(items), 8)]
    return (",\n" + indent).join(lines)


def write_trust_anchor(public):
    with open(ADS_PATH, "w", newline="\n") as f:
        f.write(ADS_TEMPLATE.format(bytes=ada_bytes(public)))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--force", action="store_true",
                        help="overwrite the existing key")
    args = parser.parse_args()

    if os.path.exists(KEY_PATH) and not args.force:
        sys.exit(f"{KEY_PATH} exists. Use --force to replace it.")

    secret = os.urandom(32)
    os.makedirs(os.path.dirname(KEY_PATH), exist_ok=True)
    with open(KEY_PATH, "w", newline="\n") as f:
        f.write("# Anchor DEVELOPMENT signing key (Ed25519 secret, hex).\n")
        f.write("# TEST KEY ONLY. Never protect a real device with it.\n")
        f.write(secret.hex() + "\n")

    write_trust_anchor(ed25519.public_key(secret))
    print(f"wrote {os.path.relpath(KEY_PATH, ROOT)}")
    print(f"wrote {os.path.relpath(ADS_PATH, ROOT)}")
    print("now: alr build, then python3 tools/pack.py")


if __name__ == "__main__":
    main()
